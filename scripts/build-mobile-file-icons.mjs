// 把 src/shared/fileIcons.ts 用到的 material-icon-theme SVG 生成为手机端字符串模块。
// 用户拍板 2026-10-13：Mac、iPhone、iPad 三端文件图标统一为 material-icon-theme 彩色类型图标。
// 手机没有 SVG 文件转换器，以 react-native-svg 的 SvgXml 渲染这些字符串。
//   node scripts/build-mobile-file-icons.mjs          重新生成
//   node scripts/build-mobile-file-icons.mjs --check  生成物与映射/上游不一致即失败
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, relative, resolve } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const PACKAGE_DIR = join(ROOT, 'node_modules/material-icon-theme');
const OUTPUT = join(ROOT, 'apps/mobile/src/files/fileIconSvgs.generated.ts');
const CHECK = process.argv.includes('--check');

const { FILE_ICON_NAMES, FILE_ICON_LIGHT_VARIANTS } = await import(
  pathToFileURL(join(ROOT, 'src/shared/fileIcons.ts')).href
);
const pkg = JSON.parse(readFileSync(join(PACKAGE_DIR, 'package.json'), 'utf8'));
const names = [...FILE_ICON_NAMES, ...Object.values(FILE_ICON_LIGHT_VARIANTS)];

const entries = names.map((name) => {
  const svg = readFileSync(join(PACKAGE_DIR, 'icons', `${name}.svg`), 'utf8').trim();
  if (/<script|on[a-z]+=|xlink:href=["']?(?!#)|href=["']?https?:/iu.test(svg)) {
    throw new Error(`${name}.svg contains script or external references`);
  }
  return `  ${JSON.stringify(name)}: ${JSON.stringify(svg)},`;
});

const content = `// Generated by scripts/build-mobile-file-icons.mjs — do not edit.
// Source: ${pkg.name}@${pkg.version} (${pkg.license}), icons/*.svg, unmodified.
// https://github.com/material-extensions/vscode-material-icon-theme
// Copyright (c) 2025 Material Extensions. Licensed under the MIT License;
// full text in node_modules/material-icon-theme/LICENSE and THIRD_PARTY_NOTICES.md.
// Icon set = FILE_ICON_NAMES + FILE_ICON_LIGHT_VARIANTS in src/shared/fileIcons.ts.

export const FILE_ICON_SOURCE = {
  package: ${JSON.stringify(pkg.name)},
  version: ${JSON.stringify(pkg.version)},
  license: ${JSON.stringify(pkg.license)},
} as const;

export const FILE_ICON_SVGS = {
${entries.join('\n')}
} as const;
`;

const label = relative(ROOT, OUTPUT);
if (CHECK) {
  let current = '';
  try {
    current = readFileSync(OUTPUT, 'utf8');
  } catch {
    // 缺文件同样按不一致处理
  }
  if (current !== content) {
    console.error(`MOBILE FILE ICON CHECK FAILED: ${label} is stale; run npm --prefix apps/mobile run icons:build`);
    process.exit(1);
  }
  console.log(`MOBILE FILE ICON CHECK OK · ${names.length} icons · ${pkg.name}@${pkg.version}`);
} else {
  writeFileSync(OUTPUT, content);
  console.log(`Generated ${label} · ${names.length} icons · ${pkg.name}@${pkg.version}`);
}
