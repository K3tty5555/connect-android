import { mkdir, mkdtemp, readFile, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

process.env.NODE_ENV = 'production';
const [{ build }, { default: react }] = await Promise.all([
  import('vite'),
  import('@vitejs/plugin-react'),
]);

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const entry = resolve(repositoryRoot, 'apps/mobile/src/room-web/room-host.tsx');
const outputPath = resolve(repositoryRoot, 'apps/mobile/assets/room/index.html');
const temporaryRoot = await mkdtemp(resolve(tmpdir(), 'connect-mobile-room-'));

try {
  await build({
    configFile: false,
    mode: 'production',
    logLevel: 'silent',
    plugins: [react()],
    define: { 'process.env.NODE_ENV': '"production"' },
    resolve: {
      alias: [
        { find: /^react$/, replacement: resolve(repositoryRoot, 'node_modules/react') },
        { find: /^react\/(.*)$/, replacement: `${resolve(repositoryRoot, 'node_modules/react')}/$1` },
        { find: /^react-dom$/, replacement: resolve(repositoryRoot, 'node_modules/react-dom') },
        { find: /^react-dom\/(.*)$/, replacement: `${resolve(repositoryRoot, 'node_modules/react-dom')}/$1` },
      ],
      dedupe: ['react', 'react-dom'],
    },
    build: {
      outDir: temporaryRoot,
      emptyOutDir: false,
      cssCodeSplit: false,
      minify: true,
      lib: {
        entry,
        name: 'ConnectMobileRoom',
        formats: ['iife'],
        fileName: () => 'room-host.js',
        cssFileName: 'style',
      },
      rollupOptions: {
        output: { inlineDynamicImports: true },
      },
    },
  });
  const [script, style] = await Promise.all([
    readFile(resolve(temporaryRoot, 'room-host.js'), 'utf8'),
    readFile(resolve(temporaryRoot, 'style.css'), 'utf8'),
  ]);
  const generated = `<!doctype html>
<!-- Generated by scripts/build-mobile-room.mjs from @lobehub/ui 5.20.3 ChatList. -->
<html lang="zh-CN">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <meta http-equiv="Content-Security-Policy" content="default-src 'none'; img-src data:; script-src 'unsafe-inline'; style-src 'unsafe-inline'">
  <style>${style.replaceAll('</style', '<\\/style')}</style>
</head>
<body>
  <div id="root"></div>
  <script>${script.replaceAll('</script', '<\\/script')}</script>
</body>
</html>
`;
  if (process.argv.includes('--check')) {
    const current = await readFile(outputPath, 'utf8').catch(() => '');
    if (current !== generated) {
      console.error('mobile room asset is stale; run npm --prefix apps/mobile run room:build');
      process.exitCode = 1;
    } else {
      console.log('mobile room asset: verified');
    }
  } else {
    await mkdir(dirname(outputPath), { recursive: true });
    await writeFile(outputPath, generated, 'utf8');
    console.log(`mobile room asset: wrote ${outputPath}`);
  }
} finally {
  await rm(temporaryRoot, { recursive: true, force: true });
}
