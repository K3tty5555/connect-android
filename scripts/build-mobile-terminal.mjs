import { readFile, writeFile } from 'node:fs/promises';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const repositoryRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const mobileRoot = resolve(repositoryRoot, 'apps/mobile');
const terminalRoot = resolve(mobileRoot, 'assets/terminal');
const outputPath = resolve(terminalRoot, 'index.html');
const upstreamCommit = 'f447274f430fd22513f6adbf9862d19524471c04';
const compositionPatchMarker = 'connect-xterm-composition-backport-55281022';

const [xtermJs, fitJs, xtermCss, xtermLicense, fitLicense, hostCss, hostJs] = await Promise.all([
  readFile(resolve(mobileRoot, 'node_modules/@xterm/xterm/lib/xterm.js'), 'utf8'),
  readFile(resolve(mobileRoot, 'node_modules/@xterm/addon-fit/lib/addon-fit.js'), 'utf8'),
  readFile(resolve(mobileRoot, 'node_modules/@xterm/xterm/css/xterm.css'), 'utf8'),
  readFile(resolve(mobileRoot, 'node_modules/@xterm/xterm/LICENSE'), 'utf8'),
  readFile(resolve(mobileRoot, 'node_modules/@xterm/addon-fit/LICENSE'), 'utf8'),
  readFile(resolve(terminalRoot, 'terminal-host.css'), 'utf8'),
  readFile(resolve(terminalRoot, 'terminal-host.js'), 'utf8'),
]);

if (!xtermJs.includes(compositionPatchMarker)) {
  throw new Error('mobile xterm bundle is missing the verified composition backport');
}

function inlineScript(source) {
  return source.replaceAll('</script', '<\\/script');
}

function inlineStyle(source) {
  return source.replaceAll('</style', '<\\/style');
}

function licenseComment(name, source) {
  return `/* @license ${name}\n${source.trim()}\n*/`;
}

const generated = `<!doctype html>
<!--
  Generated by scripts/build-mobile-terminal.mjs. Do not edit directly.
  Bundles @xterm/xterm 6.0.0 and @xterm/addon-fit 0.11.0 from upstream commit
  ${upstreamCommit}; xterm composition backport 55281022a0a5 / 2285ac6ab8a8 is applied
  with its package identity gate. Both are MIT licensed. No remote resources are loaded.
-->
<html lang="zh-CN">
<head>
  <meta charset="utf-8">
  <meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">
  <meta http-equiv="Content-Security-Policy" content="default-src 'none'; script-src 'unsafe-inline'; style-src 'unsafe-inline'">
  <style>${inlineStyle(xtermCss)}\n${inlineStyle(hostCss)}</style>
</head>
<body>
  <main id="terminal" aria-label="终端输出"></main>
  <div id="terminal-canvas-scroll" aria-label="终端只读输出">
    <div id="terminal-canvas-spacer"><canvas id="terminal-canvas"></canvas></div>
  </div>
  <pre id="terminal-watch" aria-label="终端只读输出"></pre>
  <script>${licenseComment('@xterm/xterm 6.0.0', xtermLicense)}
${inlineScript(xtermJs)}</script>
  <script>${licenseComment('@xterm/addon-fit 0.11.0', fitLicense)}
${inlineScript(fitJs)}</script>
  <script>${inlineScript(hostJs)}</script>
</body>
</html>
`;

if (process.argv.includes('--check')) {
  const current = await readFile(outputPath, 'utf8').catch(() => '');
  if (current !== generated) {
    console.error('mobile terminal asset is stale; run npm --prefix apps/mobile run terminal:build');
    process.exitCode = 1;
  } else {
    console.log('mobile terminal asset: verified');
  }
} else {
  await writeFile(outputPath, generated, 'utf8');
  console.log(`mobile terminal asset: wrote ${outputPath}`);
}
