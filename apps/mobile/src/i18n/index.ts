export function configureI18n(next: LanguagePreference | undefined, locale: string | undefined): void {
  preference = next ?? 'system';
  systemLocale = locale ?? 'zh-Hans';
}

export function currentLanguage(): ResolvedLanguage {
  if (preference !== 'system') return preference;
  return resolveLanguageFromLocales([systemLocale]);
}

function lookup(source: string): string {
  // 源语言就是简体中文，所以 zh-Hans 直接用 source。缺项一律回退 source（简体），
  // 而不是英文——`check-i18n.mjs` 的键集相等断言保证繁中不会有缺项。
  switch (currentLanguage()) {
    case 'en': return ENGLISH[source] ?? source;
    case 'zh-Hant': return TRADITIONAL[source] ?? source;
    default: return source;
  }
}

export function t(source: string, values?: Record<string, string | number>): string {
  const template = lookup(source);
  if (!values) return template;
  return template.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, key: string) => (
    Object.hasOwn(values, key) ? String(values[key]) : match
  ));
}
